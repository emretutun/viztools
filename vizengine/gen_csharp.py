"""
Sahne modelinden C# sabit sinifi uretir (NTR tarzi reji uygulamalari icin).

Uretilen dosya: scenes/<Sahne>.cs
  public static class <Sahne>
  {
      public const string Scene = "...";
      public static class Directors  { public const string KJ_IN = "$ALTBANT_ALL$KJ_IN"; ... }
      public static class Containers { public const string KJ_TEK_1_TEXT = "$...$KJ_TEK_1_TEXT"; ... }
      // yardimcilar: DirectorStart(...), SetText(...), SetActive(...)
  }
Boylece kodda elle yazilmis "...*STAGE*DIRECTOR*$X START" string'leri yerine derleyicinin
kontrol ettigi sabitler kullanilir. Sahne degisince yeniden uretilir.
"""
from __future__ import annotations

import os
import re
from collections import Counter

_KEYWORDS = {"abstract", "as", "base", "bool", "break", "byte", "case", "catch", "char", "checked", "class",
             "const", "continue", "decimal", "default", "delegate", "do", "double", "else", "enum", "event",
             "explicit", "extern", "false", "finally", "fixed", "float", "for", "foreach", "goto", "if",
             "implicit", "in", "int", "interface", "internal", "is", "lock", "long", "namespace", "new", "null",
             "object", "operator", "out", "override", "params", "private", "protected", "public", "readonly",
             "ref", "return", "sbyte", "sealed", "short", "sizeof", "stackalloc", "static", "string", "struct",
             "switch", "this", "throw", "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe",
             "ushort", "using", "virtual", "void", "volatile", "while"}


def ident(name: str) -> str:
    s = re.sub(r"[^0-9A-Za-z_]", "_", name)
    s = re.sub(r"_+", "_", s).strip("_") or "X"
    if s[0].isdigit():
        s = "_" + s
    if s in _KEYWORDS:
        s = "@" + s
    return s


def class_name(scene: str) -> str:
    s = ident(os.path.basename(scene.strip("/")))
    return s.lstrip("@")


def _unique_idents(items: list[dict], key_name="name", key_path="name_path") -> list[tuple[str, dict]]:
    """Ad tekse adi, degilse tam yoldan turetilmis tanimlayiciyi kullanir; yine cakisirsa numara ekler."""
    counts = Counter(i[key_name] for i in items)
    used: Counter = Counter()
    out = []
    for it in items:
        base = it[key_name] if counts[it[key_name]] == 1 else it[key_path].lstrip("$").replace("$", "_")
        idn = ident(base)
        used[idn] += 1
        if used[idn] > 1:
            idn = f"{idn}_{used[idn]}"
        out.append((idn, it))
    return out


_UNNAMED = {"noname", "group", "object", "Object", ""}


def short_paths(containers: list[dict]) -> dict[str, str]:
    """
    Her container icin engine'in cozdugu EN KISA tekil yol: "$ad" tekse o, degilse
    "$adliAta$ad" (engine "$A$B" yolunda B'yi A'nin altinda arar, aradaki adsiz
    seviyeleri atlar; 127.0.0.1'de dogrulandi). Hala tekil degilse bir ata daha eklenir.
    Donus: name_path -> kisa yol
    """
    full = [c["name_path"] for c in containers]
    out = {}
    for c in containers:
        parts = c["name_path"].lstrip("$").split("$")
        named = [x for x in parts if x not in _UNNAMED]
        if not named or parts[-1] in _UNNAMED:
            # Adsiz container ('noname', 'group'...) adla adreslenemez; sabiti uretilmez.
            out[c["name_path"]] = None
            continue
        chosen = None
        for k in range(1, len(named) + 1):
            cand = named[-k:]
            # cand dizisi, tam yolun icinde (sirayla, aralikli) kac container'da geciyor?
            hits = 0
            for f in full:
                fp = f.lstrip("$").split("$")
                if fp[-1] != cand[-1]:
                    continue
                i = 0
                for x in fp:
                    if i < len(cand) and x == cand[i]:
                        i += 1
                if i == len(cand):
                    hits += 1
            if hits == 1:
                chosen = cand
                break
        if chosen is None:
            # Ayni ad zinciri birden fazla container'da: engine ilk eslesene gider.
            out[c["name_path"]] = "!" + "$" + "$".join(named)
            continue
        out[c["name_path"]] = "$" + "$".join(chosen)
    return out


def _is_separator(name: str) -> bool:
    """Stage'deki gorsel ayirac director'lari: '-----', '______' gibi."""
    return bool(name) and not re.search(r"[0-9A-Za-z]", name)


def render_csharp(model: dict, namespace: str = "VizScenes") -> str:
    s = model["scene"]
    cls = class_name(s["name"])
    L = s.get("layer", "MAIN_SCENE")
    lines = []
    a = lines.append
    a("// <auto-generated>")
    a(f"//   viztools tarafindan uretildi: sahne {s['name']}, {s['scanned_at']}, kaynak: {s.get('source', 'canli engine')}")
    a("//   Elle duzenlemeyin; sahne degisince yeniden uretin (vizscan.py --csharp / arayuzde 'C# sabitleri').")
    a("// </auto-generated>")
    a("")
    a(f"namespace {namespace}")
    a("{")
    a(f"    public static class {cls}")
    a("    {")
    a(f'        public const string Scene = "{s["name"]}";')
    a(f'        public const string Layer = "{L}";')
    a("")
    a("        /// <summary>Director komut yollari ($ust$alt). Kullanim: Directors.KJ_IN</summary>")
    a("        public static class Directors")
    a("        {")
    # Tum director'lar tek bir kok director altindaysa (orn. $KJ_TUM$...), sabit adlarinda kok atilir.
    dirs = [d for d in model["directors"] if not _is_separator(d["name"])]
    roots = {d["name_path"].split("$")[1] for d in dirs if d["name_path"].count("$") >= 1}
    strip_root = len(roots) == 1 and any(d["name_path"].count("$") >= 2 for d in dirs)
    dir_items = [dict(d, name_path_id=("$" + d["name_path"].split("$", 2)[2])
                      if (strip_root and d["name_path"].count("$") >= 2) else d["name_path"]) for d in dirs]
    for idn, d in _unique_idents(dir_items, key_path="name_path_id"):
        note = "  // KAPALI: icerik okunamadi" if d.get("open") is False else ""
        a(f'            public const string {idn} = "{d["name_path"]}";{note}')
    a("        }")
    a("")
    a("        /// <summary>Container yollari: en kisa tekil '$ata$ad' bicimi (engine aradaki adsiz seviyeleri atlar).</summary>")
    a("        public static class Containers")
    a("        {")
    shorts = short_paths(model["containers"])
    # Sabit adi, engine'in cozdugu kisa yoldan turetilir: $KJ_TEK$SATIR1 -> KJ_TEK_SATIR1
    # Adsiz container'lar atlanir; ayni adla birden fazla olanlar tek sabit + uyari alir.
    con_items, seen_ambig = [], set()
    for c in model["containers"]:
        sp = shorts[c["name_path"]]
        if sp is None:
            continue
        ambiguous = sp.startswith("!")
        sp = sp.lstrip("!")
        if ambiguous:
            if sp in seen_ambig:
                continue
            seen_ambig.add(sp)
        con_items.append(dict(c, name_path_id=sp, _short=sp, _ambiguous=ambiguous))
    for idn, c in _unique_idents(con_items, key_path="name_path_id"):
        extra = []
        if c["_ambiguous"]:
            extra.append("TEKIL DEGIL: sahnede ayni adla birden fazla; engine ilk eslesene gider")
        if c.get("text"):
            extra.append("text: " + c["text"].replace("\n", " ")[:60])
        if c.get("plugins"):
            extra.append(", ".join(c["plugins"][:3]))
        note = ("  // " + " | ".join(extra)) if extra else ""
        a(f'            public const string {idn} = "{c["_short"]}";{note}')
    a("        }")
    a("")
    a("        // ---- Komut yardimcilari (engine'e gonderilecek metni uretir; gondermez) ----")
    a(f'        public static string DirectorStart(string director, string layer = Layer) => $"{{layer}}*STAGE*DIRECTOR*{{director}} START";')
    a(f'        public static string DirectorContinue(string director, string layer = Layer) => $"{{layer}}*STAGE*DIRECTOR*{{director}} CONTINUE";')
    a(f'        public static string DirectorStop(string director, string layer = Layer) => $"{{layer}}*STAGE*DIRECTOR*{{director}} STOP";')
    a(f'        public static string DirectorReset(string director, string layer = Layer) => $"{{layer}}*STAGE*DIRECTOR*{{director}}*GOTO_TRIO 0";')
    a(f'        public static string SetText(string container, string text, string layer = Layer) => $"{{layer}}*TREE*{{container}}*GEOM*TEXT SET {{text}}";')
    a(f'        public static string SetActive(string container, bool on, string layer = Layer) => $"{{layer}}*TREE*{{container}}*ACTIVE SET {{(on ? 1 : 0)}}";')
    a(f'        public static string SetPosition(string container, float x, float y, float z, string layer = Layer) => $"{{layer}}*TREE*{{container}}*TRANSFORMATION*POSITION SET {{x}} {{y}} {{z}}";')
    a(f'        public static string SetImage(string container, string imagePath, string layer = Layer) => $"{{layer}}*TREE*{{container}}*IMAGE SET {{imagePath}}";')
    a("    }")
    a("}")
    a("")
    return "\n".join(lines)


def write_csharp(model: dict, out_dir: str, namespace: str = "VizScenes") -> str:
    """<out_dir>/<sahne>/<sahne>.cs (sablon ve JSON ile ayni klasor)."""
    from .template import scene_dir, scene_base
    path = os.path.join(scene_dir(model, out_dir), f"{scene_base(model)}.cs")
    with open(path, "w", encoding="utf-8-sig") as f:
        f.write(render_csharp(model, namespace))
    return path
